"""Static validation for AI-generated remediation artefacts.

Nothing generated by Agent 3 is ever executed by the platform. This module:

* syntax-checks bash with ``bash -n`` (parse only, never runs) and Python
  with ``ast.parse``;
* parses AWS WAF / security-group rules as JSON;
* sanity-checks iptables/nftables/ufw/nginx rule text;
* flags destructive or supply-chain-risky patterns and assigns a risk level.

The result is attached to each patch so the approval UI can show exactly
what a reviewer is signing off on.
"""

from __future__ import annotations

import ast
import asyncio
import json
import re
import shutil
import tempfile
from pathlib import Path

from agents.schemas import FirewallRule, PatchScript, ScriptValidation

_HIGH_RISK: list[tuple[re.Pattern[str], str]] = [
    (re.compile(r"\brm\s+-[a-z]*r[a-z]*f?\s+(/|/\*|~|\$HOME)(\s|$)"), "Recursive delete of a root/home path"),
    (re.compile(r"\bmkfs(\.\w+)?\b"), "Filesystem format command"),
    (re.compile(r"\bdd\s+[^\n]*\bof=/dev/"), "Raw write to a block device"),
    (re.compile(r"(curl|wget)[^\n|]*\|\s*(sudo\s+)?(ba|z)?sh\b"), "Pipes a remote download straight into a shell"),
    (re.compile(r":\(\)\s*\{\s*:\|:&\s*\};:"), "Fork bomb"),
    (re.compile(r"\bchmod\s+(-R\s+)?777\b"), "World-writable permissions"),
    (re.compile(r"\biptables\s+(-F|--flush)\b(?![^\n]*-t)"), "Flushes all firewall rules"),
    (re.compile(r"\b(shutdown|reboot|halt|poweroff)\b"), "Host shutdown/reboot"),
    (re.compile(r"\beval\s+\"?\$\("), "eval of command substitution"),
    (re.compile(r"\bos\.system\(|subprocess\.[a-z_]+\([^)]*shell\s*=\s*True"), "Shell execution from Python"),
]
_MEDIUM_RISK: list[tuple[re.Pattern[str], str]] = [
    (re.compile(r"\bsystemctl\s+(restart|stop)\b"), "Restarts/stops a service (brief availability impact)"),
    (re.compile(r"\b(apt(-get)?|yum|dnf)\s+(install|upgrade|remove)\b"), "Changes installed packages"),
    (re.compile(r"\baws\s+iam\s+(delete|update|detach|put)"), "Modifies IAM configuration"),
    (re.compile(r"\biptables\s+-[AI]\b.*-j\s+DROP"), "Adds blocking firewall rule"),
    (re.compile(r"\bsed\s+-i\b"), "In-place config file edit"),
]


def _assess(text: str) -> tuple[str, list[str]]:
    findings = [msg for pattern, msg in _HIGH_RISK if pattern.search(text)]
    if findings:
        return "high", findings
    medium = [msg for pattern, msg in _MEDIUM_RISK if pattern.search(text)]
    return ("medium" if medium else "low"), medium


async def _bash_syntax_ok(script: str, limit_s: float = 5.0) -> tuple[bool, str | None]:
    bash = shutil.which("bash")
    if bash is None:
        return True, "bash not available on this host; syntax check skipped"
    with tempfile.NamedTemporaryFile("w", suffix=".sh", delete=False) as fh:
        fh.write(script)
        path = Path(fh.name)
    try:
        proc = await asyncio.create_subprocess_exec(
            bash, "-n", str(path),
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE,
        )
        try:
            _, stderr = await asyncio.wait_for(proc.communicate(), timeout=limit_s)
        except TimeoutError:
            proc.kill()
            await proc.wait()
            return False, "bash -n timed out"
        if proc.returncode == 0:
            return True, None
        return False, stderr.decode("utf-8", "replace").replace(str(path), "script").strip()
    finally:
        path.unlink(missing_ok=True)


async def validate_patch_script(patch: PatchScript) -> ScriptValidation:
    findings: list[str] = []
    if patch.language == "bash":
        ok, message = await _bash_syntax_ok(patch.script)
        if message:
            findings.append(message)
        if not patch.script.lstrip().startswith("#!"):
            findings.append("Missing shebang line")
        if "set -e" not in patch.script:
            findings.append("Script does not use 'set -euo pipefail'")
        rb_ok, rb_message = await _bash_syntax_ok(patch.rollback_script) if patch.rollback_script.strip() else (False, "Empty rollback script")
        if not rb_ok:
            findings.append(f"Rollback script invalid: {rb_message}")
    else:
        try:
            ast.parse(patch.script)
            ok = True
        except SyntaxError as exc:
            ok = False
            findings.append(f"Python syntax error line {exc.lineno}: {exc.msg}")
    risk, risk_findings = _assess(patch.script)
    return ScriptValidation(
        target=f"patch_script:{patch.filename}",
        kind=patch.language,
        syntax_ok=ok,
        risk_level=risk,
        findings=findings + risk_findings,
    )


def validate_firewall_rule(rule: FirewallRule, index: int) -> ScriptValidation:
    findings: list[str] = []
    ok = True
    text = rule.rule.strip()
    if rule.platform in {"aws_waf", "aws_security_group"}:
        try:
            json.loads(text)
        except json.JSONDecodeError as exc:
            ok = False
            findings.append(f"Rule is not valid JSON: {exc.msg} (line {exc.lineno})")
    elif rule.platform in {"iptables", "nftables", "ufw"}:
        lines = [ln.strip() for ln in text.splitlines() if ln.strip() and not ln.strip().startswith("#")]
        bad = [ln for ln in lines if not re.match(rf"^(sudo\s+)?({rule.platform}|ip6tables|nft)\b", ln)]
        if not lines or bad:
            ok = False
            findings.append(f"Every line must be a {rule.platform} command")
    elif rule.platform == "nginx":
        if text.count("{") != text.count("}"):
            ok = False
            findings.append("Unbalanced braces in nginx snippet")
        if not re.search(r";\s*($|\})", text, re.M):
            findings.append("No nginx directive terminator ';' found")
    risk, risk_findings = _assess(text)
    return ScriptValidation(
        target=f"firewall_rule:{index}",
        kind=rule.platform,
        syntax_ok=ok,
        risk_level=risk,
        findings=findings + risk_findings,
    )
